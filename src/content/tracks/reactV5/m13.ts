import type { Lesson } from '../../types';
import { app, chat, check, explore, lesson, recap, reveal, tapbug, tapPage, truth, UI } from './kit';

const THEME = [
  'import { createContext, useContext, useState } from "react";',
  '',
  'const ThemeContext = createContext("light");',
  '',
  'function DishCard({ name }) {',
  '  const theme = useContext(ThemeContext);',
  '  return <p className={"card " + theme}>{name}</p>;',
  '}',
  '',
  'function Menu() {',
  '  return (',
  '    <div>',
  '      <DishCard name="Lemon Tea" />',
  '      <DishCard name="Cheese Toast" />',
  '    </div>',
  '  );',
  '}',
  '',
  'function App() {',
  '  const [theme, setTheme] = useState("light");',
  '  function flip() {',
  '    const next = theme === "light" ? "dark" : "light";',
  '    setTheme(next);',
  '    console.log("Theme: " + next);',
  '  }',
  '  return (',
  '    <ThemeContext value={theme}>',
  '      <button id="flip" onClick={flip}>Switch theme</button>',
  '      <Menu />',
  '    </ThemeContext>',
  '  );',
  '}',
];

const DARK = `${UI}
.dark { background: #1F2A30; color: #F4FBFD; border-color: #1F2A30; }`;

const REDUCER = [
  'import { useReducer } from "react";',
  '',
  'function cartReducer(cart, action) {',
  '  switch (action.type) {',
  '    case "add":',
  '      return [...cart, action.dish];',
  '    case "clear":',
  '      return [];',
  '    default:',
  '      return cart;',
  '  }',
  '}',
  '',
  'function App() {',
  '  const [cart, dispatch] = useReducer(cartReducer, []);',
  '  console.log("Cart: " + (cart.join(", ") || "empty"));',
  '  return (',
  '    <div className="card">',
  '      <button id="tea" onClick={() => dispatch({ type: "add", dish: "Lemon Tea" })}>Add tea</button>',
  '      <button id="toast" onClick={() => dispatch({ type: "add", dish: "Cheese Toast" })}>Add toast</button>',
  '      <button id="clear" onClick={() => dispatch({ type: "clear" })}>Clear</button>',
  '      <p>{cart.join(", ") || "Cart is empty"}</p>',
  '    </div>',
  '  );',
  '}',
];

const BOTH = [
  'import { createContext, useContext, useReducer } from "react";',
  '',
  'const CartContext = createContext(null);',
  '',
  'function cartReducer(cart, action) {',
  '  if (action.type === "add") return [...cart, action.dish];',
  '  if (action.type === "clear") return [];',
  '  return cart;',
  '}',
  '',
  'function AddButton({ id, dish }) {',
  '  const { dispatch } = useContext(CartContext);',
  '  return <button id={id} onClick={() => dispatch({ type: "add", dish })}>Add {dish}</button>;',
  '}',
  '',
  'function CartBadge() {',
  '  const { cart } = useContext(CartContext);',
  '  console.log("Badge shows " + cart.length);',
  '  return <p className="ok">🛒 {cart.length} in cart</p>;',
  '}',
  '',
  'function App() {',
  '  const [cart, dispatch] = useReducer(cartReducer, []);',
  '  return (',
  '    <CartContext value={{ cart, dispatch }}>',
  '      <CartBadge />',
  '      <div className="card">',
  '        <AddButton id="tea" dish="Lemon Tea" />',
  '        <AddButton id="toast" dish="Cheese Toast" />',
  '      </div>',
  '    </CartContext>',
  '  );',
  '}',
];

export const R_M13: Lesson[] = [
  lesson('r-context-1', 'Context', 6, [
    chat(['Passing a prop through many layers that don’t use it is called prop drilling.', 'Context lets a parent share a value with every component below it, however deep.']),
    tapPage('A theme for the whole menu', 'Switch the theme.', app(THEME.join('\n'), DARK), 'Theme: dark', [{ click: '#flip' }], 'Menu never touches the theme. DishCard reads it from context.'),
    explore('Context in 3 steps', THEME, [
      [3, '1 · Make a context, with a default value.'],
      [27, '2 · Give it a value for everything inside.'],
      [6, '3 · Read it in any component below.', '.card'],
      [10, 'Menu passes nothing on.'],
    ], { page: app(THEME.join('\n'), DARK), minTaps: 3 }),
    check('Which reads the value of ThemeContext?', ['useContext(ThemeContext)', 'ThemeContext.value', 'useState(ThemeContext)', 'props.theme'], 'useContext finds the closest value above.', 'Which one is a hook?', { mono: true }),
    reveal('When to use context', [
      ['Good for', 'A theme, the signed-in user, the language: things many parts need.'],
      ['Try props first', 'If only one or two layers need it, props are clearer.'],
      ['The default', 'createContext("light") gives "light" when nothing above sets a value.'],
      ['Older code', 'You may see <ThemeContext.Provider value={…}>. It does the same.'],
    ]),
    tapbug('The theme is always undefined', ['const theme = useContext("ThemeContext");'], [[1, '"ThemeContext"', 'ThemeContext']], 'Pass the context itself, not its name as text.'),
    recap([
      ['📡', 'Context shares a value with everything below'],
      ['🧵', 'No more passing props through every layer'],
      ['👀', 'Read it with useContext'],
    ]),
  ], 'intermediate'),

  lesson('r-b-13-2', 'useReducer', 6, [
    reveal('useReducer', [
      ['A reducer', 'A function (state, action) that gives back the next state.'],
      ['dispatch(action)', 'Say what happened, like { type: "add", dish }.'],
      ['One place', 'Every way the state can change is in one function.'],
      ['Pure', 'No fetch, and no changing the old state: just work out the new one.'],
    ]),
    tapPage('A cart run by a reducer', 'Add a tea, then a toast.', app(REDUCER.join('\n')), 'Cart: Lemon Tea, Cheese Toast', [{ click: '#tea' }, { click: '#toast' }], 'The buttons only say what happened. The reducer decides what changes.'),
    explore('Reading the reducer', REDUCER, [
      [3, 'The reducer gets the current cart and an action.'],
      [5, 'Each case is one kind of change.'],
      [6, 'It gives back a new array, never a changed old one.'],
      [15, 'useReducer gives you the state and dispatch.'],
      [19, 'A tap sends an action.', '#tea'],
    ], { page: app(REDUCER.join('\n')), minTaps: 3 }),
    check('What does dispatch({ type: "clear" }) do?', ['Calls the reducer with that action and draws what it gives back', 'Clears the cart directly', 'Deletes the reducer', 'Nothing until the page reloads'], 'React runs your reducer, then draws.', 'Who decides the new state?', { mono: false }),
    tapbug('Tapping Add changes nothing on screen', ['case "add":', '  cart.push(action.dish);', '  return cart;'], [[2, 'cart.push(action.dish);', 'const next = [...cart, action.dish];'], [3, 'return cart;', 'return next;']], 'A reducer must give back a new array, not change the old one.'),
    recap([
      ['🎛', 'A reducer holds every change in one place'],
      ['📨', 'dispatch says what happened'],
      ['🆕', 'Always give back new state'],
    ]),
  ], 'intermediate'),

  lesson('r-b-13-3', 'Context and a reducer together', 6, [
    chat(['Put the two together: a reducer manages the state, and context shares it.', 'Any component, however deep, can read the cart and send actions, with no props passed down.']),
    tapPage('One cart for the whole app', 'Add a tea and a toast.', app(BOTH.join('\n')), 'Badge shows 2', [{ click: '#tea' }, { click: '#toast' }], 'AddButton and CartBadge never pass props to each other.'),
    explore('How it fits together', BOTH, [
      [23, 'App keeps the cart in a reducer.'],
      [25, 'Context shares the cart and dispatch.'],
      [12, 'AddButton takes dispatch from context.', '#tea'],
      [17, 'CartBadge takes the cart from context.', '.ok'],
    ], { page: app(BOTH.join('\n')), minTaps: 3 }),
    check('Why put dispatch in context?', ['So deep components can change state without props passed down', 'It makes reducers faster', 'dispatch only works in context', 'To hide the cart from App'], 'Any component below can send an action.', 'Who needs to change the cart?', { mono: false }),
    truth([
      ['Context shares a value; a reducer manages its changes', true, 'They do different jobs.'],
      ['Every app needs context and a reducer', false, 'Start with useState and props. Add these as the app grows.'],
      ['A component using useContext draws again when the value changes', true, 'So the badge updates.'],
    ]),
    recap([
      ['🤝', 'Reducer for changes, context for sharing'],
      ['🌳', 'Any component can read and dispatch'],
      ['🌱', 'Start simple; add these as the app grows'],
    ]),
  ], 'intermediate'),
];
