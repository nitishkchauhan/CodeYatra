// Builds src/lib/web/reactRuntime.ts: React 19, ReactDOM, React Router and a JSX compiler (sucrase) in one small
// script, so React lesson pages run real React offline; and src/lib/web/nextRuntime.ts, the teaching copy of Next.js.
// Run after upgrading react, react-dom, react-router or sucrase, or after changing scripts/next-runtime.js or scripts/node-runtime.js:
//   node scripts/build-react-runtime.mjs
// The test in src/lib/__tests__/reactPage.test.ts checks the file is up to date with the installed versions.
import { build, transform } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const version = (p) => JSON.parse(readFileSync(new URL(`../node_modules/${p}/package.json`, import.meta.url), 'utf8')).version;

const entry = `
import * as React from 'react';
import * as ReactDOMClient from 'react-dom/client';
import { createPortal, flushSync, useFormStatus } from 'react-dom';
import { transform } from 'sucrase';
import { MemoryRouter, Routes, Route, Link, NavLink, Outlet, Navigate, useParams, useNavigate, useLocation } from 'react-router';
window.React = React;
// react-dom/client (createRoot) and react-dom (createPortal) share one global.
window.ReactDOM = { ...ReactDOMClient, createPortal, flushSync, useFormStatus };
// A lesson page has no real address bar, so BrowserRouter is a MemoryRouter that starts at "/": links and routes
// work exactly the same inside the page.
window.ReactRouter = { BrowserRouter: MemoryRouter, MemoryRouter, Routes, Route, Link, NavLink, Outlet, Navigate, useParams, useNavigate, useLocation };
window.__cyJsx = (code) => transform(code, { transforms: ['jsx'], production: true, jsxRuntime: 'classic' }).code;
`;

const out = await build({
  stdin: { contents: entry, resolveDir: new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), loader: 'js' },
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2019',
  write: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const code = out.outputFiles[0].text;
const versions = `react ${version('react')}, react-dom ${version('react-dom')}, react-router ${version('react-router')}, sucrase ${version('sucrase')}`;
writeFileSync(
  new URL('../src/lib/web/reactRuntime.ts', import.meta.url),
  `// Generated by scripts/build-react-runtime.mjs from ${versions}. Do not edit.\nexport const REACT_RUNTIME_VERSIONS = ${JSON.stringify(versions)};\nexport const REACT_RUNTIME = ${JSON.stringify(code)};\n`,
);
console.log(`reactRuntime.ts: ${(code.length / 1024).toFixed(0)} KB (${versions})`);

// The teaching copy of Next.js (scripts/next-runtime.js) runs on that React, in Next.js lesson pages.
const next = (await transform(readFileSync(new URL('./next-runtime.js', import.meta.url), 'utf8'), { minify: true, target: 'es2019', legalComments: 'none' })).code;
writeFileSync(
  new URL('../src/lib/web/nextRuntime.ts', import.meta.url),
  `// Generated by scripts/build-react-runtime.mjs from scripts/next-runtime.js. Do not edit.
export const NEXT_RUNTIME = ${JSON.stringify(next)};
`,
);
console.log(`nextRuntime.ts: ${(next.length / 1024).toFixed(0)} KB`);

// The teaching copy of Node.js (scripts/node-runtime.js) runs Node.js lesson programs in a terminal page.
const nodeRt = (await transform(readFileSync(new URL('./node-runtime.js', import.meta.url), 'utf8'), { minify: true, target: 'es2019', legalComments: 'none' })).code;
writeFileSync(
  new URL('../src/lib/web/nodeRuntime.ts', import.meta.url),
  `// Generated by scripts/build-react-runtime.mjs from scripts/node-runtime.js. Do not edit.\nexport const NODE_RUNTIME = ${JSON.stringify(nodeRt)};\n`,
);
console.log(`nodeRuntime.ts: ${(nodeRt.length / 1024).toFixed(0)} KB`);
