// Builds src/lib/web/reactRuntime.ts: React 19, ReactDOM and a JSX compiler (sucrase) in one small script, so React
// lesson pages run real React offline. Run after upgrading react, react-dom or sucrase:
//   node scripts/build-react-runtime.mjs
// The test in src/lib/__tests__/reactPage.test.ts checks the file is up to date with the installed versions.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const version = (p) => JSON.parse(readFileSync(new URL(`../node_modules/${p}/package.json`, import.meta.url), 'utf8')).version;

const entry = `
import * as React from 'react';
import * as ReactDOM from 'react-dom/client';
import { transform } from 'sucrase';
window.React = React;
window.ReactDOM = ReactDOM;
window.__cyJsx = (code) => transform(code, { transforms: ['jsx'], production: true, jsxRuntime: 'classic' }).code;
`;

const out = await build({
  stdin: { contents: entry, resolveDir: new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'), loader: 'js' },
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2019',
  write: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const code = out.outputFiles[0].text;
const versions = `react ${version('react')}, react-dom ${version('react-dom')}, sucrase ${version('sucrase')}`;
writeFileSync(
  new URL('../src/lib/web/reactRuntime.ts', import.meta.url),
  `// Generated by scripts/build-react-runtime.mjs from ${versions}. Do not edit.\nexport const REACT_RUNTIME_VERSIONS = ${JSON.stringify(versions)};\nexport const REACT_RUNTIME = ${JSON.stringify(code)};\n`,
);
console.log(`reactRuntime.ts: ${(code.length / 1024).toFixed(0)} KB (${versions})`);
